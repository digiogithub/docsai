/// The package a deck with no ODF package of its own is generated on.
///
/// Generated by `corpus/generate.py` (`odf_default_template`) from the XML in
/// that file, so every byte of it is reviewable source rather than a binary of
/// unknown provenance, and `python3 corpus/generate.py --check` fails if the
/// checked-in file stops being what the generator produces.
pub(super) const TEMPLATE: &[u8] = include_bytes!("../../assets/default-template.odp");

/// The prefix the automatic styles a *generated* body needs carry.
///
/// Not [`super::write`]'s `ds`: the splicing pass runs over the package this
/// module produced and mints its own names from the same counter, so sharing a
/// prefix would let a second `dgP1` be minted over the first.
const STYLE_PREFIX: &str = "dg";

/// The `text:list-style` a generated ordered list points at.
///
/// ODF states «this list is numbered» **in a list style**, never on the list
/// itself: `text:list` carries only a `text:style-name`, and
/// [`crate::odt::body::read_blocks`] decides `ordered` by resolving that name.
/// A deck crossing from PresentationML carries `List::ordered` and no list
/// definition at all — an OOXML list is numbered by its own `a:buAutoNum` —
/// so a generated list with no style is a list ODF calls unordered, which is
/// how a numbered list crossed as a bulleted one before this existed.
const ORDERED_LIST_STYLE: &str = "dgLNum";

/// How deep the generated list style declares levels.
///
/// [`ListDef::is_ordered_at`] is asked with the list's absolute nesting depth,
/// so a style that stops at level 1 makes a numbered list bulleted the moment
/// it is nested. Ten is what every producer of these files writes.
const LIST_LEVELS: usize = 10;

/// The master page the template declares, and the only one it has.
const MASTER: &str = "Default";

/// The template's two `style:presentation-page-layout`: a title with an outline
/// under it, and a title alone.
const LAYOUT_TITLE_BODY: &str = "AL1T19";
const LAYOUT_TITLE_ONLY: &str = "AL2T1";

/// The rectangles the template's page layouts put a title and a body in.
///
/// A shape that states its own geometry keeps it — this is the fallback for a
/// placeholder that states none, which is what a placeholder resolved against
/// its layout looks like in the IR ([`docsai_model::presentation::ShapeGeometry`]
/// documents the absence as *inherited*). The numbers are the template's own,
/// in the centimetres ODF measures in.
/// The page the template declares, in the units [`Size`] measures in.
///
/// The model's own `Presentation::slide_size` replaces it whenever the model
/// states one — but a deck that came through DocMark does not: **DocMark-P
/// carries no canvas size**, so a deck read from its Markdown alone knows the
/// EMU a shape sits at and not the page those EMU are relative to. That is a
/// gap in the profile, not in this writer, and closing it is a normative change
/// to `docs/docmark-specification.md` §11.2's front-matter keys. What this
/// writer owes meanwhile is to say when it matters, which
/// [`warn_outside_the_page`] does.
const TEMPLATE_PAGE: Size = Size::new(Length::from_emu(10_080_000), Length::from_emu(5_670_000));

const TITLE_BOX: &str = r#"svg:x="1.4cm" svg:y="0.837cm" svg:width="25.2cm" svg:height="2.629cm""#;
const BODY_BOX: &str = r#"svg:x="1.4cm" svg:y="3.685cm" svg:width="25.2cm" svg:height="9.906cm""#;

/// The package the rest of the writer works on, with the model's pages in it.
///
/// The report gains one warning for the substitution itself and one per
/// construct that could not cross — never one for a construct that did.
pub(super) fn generate(
    deck: &Presentation,
    assets: &dyn AssetStore,
    report: &mut ConversionReport,
) -> Result<Vec<u8>, WriteError> {
    let mut package = Package::open(std::io::Cursor::new(TEMPLATE))
        .map_err(|e| WriteError::Invalid(format!("the embedded ODF template: {e}")))?;
    let source = package
        .text(CONTENT_PART)
        .map_err(|e| WriteError::Invalid(format!("the embedded ODF template: {e}")))?
        .to_string();
    let root = Element::parse(CONTENT_PART, source.as_bytes())
        .map_err(|e| WriteError::Invalid(format!("the embedded ODF template: {e}")))?;

    let mut pages = String::new();
    let mut pictures: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    let styles;
    {
        let mut ctx = WriterCtx {
            assets,
            report,
            auto: AutoStyles::with_prefix(STYLE_PREFIX),
            pictures: BTreeMap::new(),
            pic_seq: 0,
            note_seq: 0,
        };
        let page = if deck.slide_size.width.emu() > 0 && deck.slide_size.height.emu() > 0 {
            deck.slide_size
        } else {
            TEMPLATE_PAGE
        };
        for (index, slide) in deck.slides.iter().enumerate() {
            write_page(slide, index, page, &mut ctx, &mut pages)?;
        }
        let mut declared = if ctx.auto.is_empty() {
            String::new()
        } else {
            automatic_style_bodies(&ctx.auto)
        };
        if pages.contains(ORDERED_LIST_STYLE) {
            crate::odt::write::write_list_style(
                &ListId::new(ORDERED_LIST_STYLE),
                &ordered_list_def(),
                &mut declared,
            );
        }
        styles = declared;
        pictures.append(&mut ctx.pictures);
    }

    let content = splice(&source, &root, &pages, &styles)?;
    package.insert(CONTENT_PART, content.into_bytes());
    package.insert("meta.xml", write_meta_xml(&deck.meta).into_bytes());
    resize_page(&mut package, deck.slide_size)?;

    if !pictures.is_empty() {
        let entries: Vec<(String, String)> = pictures
            .keys()
            .map(|path| (path.clone(), guess_image_mime(path)))
            .collect();
        let manifest = super::write::manifest_with(&package, &entries)
            .map_err(|why| WriteError::Invalid(format!("`{MANIFEST_PART}`: {why}")))?;
        for (path, bytes) in pictures {
            package.insert(&path, bytes);
        }
        package.insert(MANIFEST_PART, manifest);
    }

    let mut out = std::io::Cursor::new(Vec::new());
    package
        .write_to(&mut out)
        .map_err(|e| WriteError::Invalid(format!("the generated package: {e}")))?;
    Ok(out.into_inner())
}

/// The template's page, resized to the canvas the model states.
///
/// **Not decoration.** Every rectangle a generated frame carries is the model's
/// own, in EMU, relative to `Presentation::slide_size`; the template's page is
/// 28 × 15.75 cm and a `.pptx` is 33.87 × 19.05 cm. Leaving the template's
/// number there put a placeholder near the bottom of a PowerPoint slide off the
/// bottom of the ODF page — the deck opened, the text was in the file, and a
/// person looking at it could not see it.
///
/// The edit is a splice into the one `style:page-layout-properties` the
/// template declares, made through the parse rather than by scanning, and it is
/// the only reason this writer ever touches `styles.xml`.
fn resize_page(package: &mut Package, size: Size) -> Result<(), WriteError> {
    if size.width.emu() <= 0 || size.height.emu() <= 0 {
        return Ok(());
    }
    let source = package
        .text(STYLES_PART)
        .map_err(|e| WriteError::Invalid(format!("the embedded ODF template: {e}")))?
        .to_string();
    let root = Element::parse(STYLES_PART, source.as_bytes())
        .map_err(|e| WriteError::Invalid(format!("the embedded ODF template: {e}")))?;
    let properties = root
        .child("automatic-styles")
        .and_then(|auto| auto.children_named("page-layout").next())
        .and_then(|layout| layout.children_named("page-layout-properties").next())
        .ok_or_else(|| {
            WriteError::Invalid(
                "the embedded ODF template declares no <style:page-layout-properties>".into(),
            )
        })?;
    let mut replacement = format!(
        r#"<style:page-layout-properties fo:page-width="{}" fo:page-height="{}""#,
        format_cm(size.width),
        format_cm(size.height)
    );
    for (name, value) in &properties.attrs {
        if name != "fo:page-width" && name != "fo:page-height" {
            replacement.push_str(&format!(r#" {}="{}""#, name, esc_attr(value)));
        }
    }
    replacement.push_str("/>");
    let mut out = String::with_capacity(source.len() + replacement.len());
    out.push_str(&source[..properties.span.start]);
    out.push_str(&replacement);
    out.push_str(&source[properties.span.end..]);
    package.insert(STYLES_PART, out.into_bytes());
    Ok(())
}

/// Puts the generated pages inside `office:presentation` and the automatic
/// styles they need inside `office:automatic-styles`.
///
/// Both anchors are found through the parse and never by scanning for a start
/// tag, for the reason [`super::write::open_tag`] states: an attribute value
/// may legally contain `>`.
fn splice(source: &str, root: &Element, pages: &str, styles: &str) -> Result<String, WriteError> {
    let presentation = root.path(&["body", "presentation"]).ok_or_else(|| {
        WriteError::Invalid(
            "the embedded ODF template has no <office:presentation> to write into".into(),
        )
    })?;
    let auto = root.child("automatic-styles").ok_or_else(|| {
        WriteError::Invalid(
            "the embedded ODF template declares no <office:automatic-styles>".into(),
        )
    })?;
    // The pages go before whatever `office:presentation` already holds —
    // `presentation:settings`, which ODF requires after the pages, not before.
    let at_pages = match presentation.children().next() {
        Some(first) => first.span.start,
        None => presentation.span.end - format!("</{}>", qualified(presentation)).len(),
    };
    let at_styles = match auto.children().last() {
        Some(last) => last.span.end,
        None => auto.span.end - format!("</{}>", qualified(auto)).len(),
    };
    let (first, second) = if at_styles <= at_pages {
        ((at_styles, styles), (at_pages, pages))
    } else {
        ((at_pages, pages), (at_styles, styles))
    };
    let mut out = String::with_capacity(source.len() + pages.len() + styles.len());
    out.push_str(&source[..first.0]);
    out.push_str(first.1);
    out.push_str(&source[first.0..second.0]);
    out.push_str(second.1);
    out.push_str(&source[second.0..]);
    Ok(out)
}

/// One `draw:page`, its frames and its notes.
fn write_page(
    slide: &Slide,
    index: usize,
    page: Size,
    ctx: &mut WriterCtx<'_>,
    out: &mut String,
) -> Result<(), WriteError> {
    let name = slide
        .name
        .clone()
        .unwrap_or_else(|| format!("page{}", index + 1));
    out.push_str(&format!(
        r#"<draw:page draw:name="{}" draw:style-name="dp1" draw:master-page-name="{MASTER}" presentation:presentation-page-layout-name="{}">"#,
        esc_attr(&name),
        layout_for(slide)
    ));
    for shape in &slide.shapes {
        warn_outside_the_page(shape, &name, page, ctx);
        write_shape(shape, &name, ctx, out)?;
    }
    if let Some(notes) = slide.notes.as_ref().filter(|n| !n.is_empty()) {
        let mut body = String::new();
        write_blocks(&with_list_styles(notes), ctx, &mut body)?;
        out.push_str(
            r#"<presentation:notes draw:style-name="dp1"><draw:frame presentation:style-name="pr-notes" draw:layer="layout" svg:x="3.5cm" svg:y="9.5cm" svg:width="14cm" svg:height="10cm" presentation:class="notes"><draw:text-box>"#,
        );
        out.push_str(&body);
        out.push_str("</draw:text-box></draw:frame></presentation:notes>");
    }
    if !slide.comments.is_empty() {
        ctx.report.warn(Warning::Degraded {
            what: format!("{} comment(s) on page `{name}`", slide.comments.len()),
            why: "an ODF annotation is markup no writer in this project writes, and this \
                  deck has no ODF package to keep one in, so the comments were not written"
                .into(),
        });
    }
    out.push_str("</draw:page>");
    Ok(())
}

/// Says so when a shape's rectangle falls outside the page it is written onto.
///
/// A `.pptx` states its geometry in EMU relative to its own `p:sldSz`, and a
/// crossed deck lands on a page of the template's size unless the model states
/// one — see [`TEMPLATE_PAGE`]. A 4:3 deck crossing onto a 16:9 page puts its
/// lowest placeholder below the bottom edge: the text is in the file, the file
/// opens, and a person looking at the slide cannot see it. That is a visible
/// loss and it gets a warning rather than a shrug.
fn warn_outside_the_page(shape: &Shape, page_name: &str, page: Size, ctx: &mut WriterCtx<'_>) {
    let (Some(pos), Some(size)) = (shape.geometry.pos, shape.geometry.size) else {
        return;
    };
    let right = pos.x.emu() + size.width.emu();
    let bottom = pos.y.emu() + size.height.emu();
    if right <= page.width.emu() && bottom <= page.height.emu() {
        return;
    }
    ctx.report.warn(Warning::Degraded {
        what: format!("the placement of a shape on page `{page_name}`"),
        why: format!(
            "it reaches {} × {} on a page of {} × {}, so part of it falls outside the \
page and a reader will not see it: the model states its geometry in the canvas its own \
dialect declared and DocMark-P carries no canvas size, so this deck was written on the \
template's page",
            format_cm(Length::from_emu(right)),
            format_cm(Length::from_emu(bottom)),
            format_cm(page.width),
            format_cm(page.height)
        ),
    });
}

/// Which of the template's two page layouts a slide is written against.
///
/// The rule is the shape of the content, exactly as the `.pptx` generator's is
/// (analysis §6.6): a slide whose placeholders include a body-like one gets the
/// layout that declares an outline rectangle, and a slide that does not gets
/// the title-only one. A wrong guess costs a placeholder its inherited
/// geometry and nothing else, because every generated frame states its own.
fn layout_for(slide: &Slide) -> &'static str {
    let has_body = slide
        .shapes
        .iter()
        .any(|shape| matches!(&shape.kind, ShapeKind::Placeholder(ph) if ph.ph_type.is_body()));
    if has_body {
        LAYOUT_TITLE_BODY
    } else {
        LAYOUT_TITLE_ONLY
    }
}

/// The definition [`ORDERED_LIST_STYLE`] declares: `1.` at every level.
fn ordered_list_def() -> ListDef {
    ListDef {
        levels: (0..LIST_LEVELS)
            .map(|_| ListLevel::new(NumFormat::Decimal, "%1."))
            .collect(),
    }
}

/// The blocks with a list style name on every ordered list that has none.
///
/// A copy rather than an edit of the model: the deck belongs to the caller and
/// this is a fact about the file being written, not about the deck.
fn with_list_styles(blocks: &[Block]) -> Vec<Block> {
    blocks
        .iter()
        .map(|block| match block {
            Block::List(list) => Block::List(with_list_style(list)),
            other => other.clone(),
        })
        .collect()
}

fn with_list_style(list: &List) -> List {
    let mut out = list.clone();
    if out.ordered && out.def.is_none() {
        out.def = Some(ListId::new(ORDERED_LIST_STYLE));
    }
    for item in &mut out.items {
        item.blocks = with_list_styles(&item.blocks);
    }
    out
}

fn write_shape(
    shape: &Shape,
    page: &str,
    ctx: &mut WriterCtx<'_>,
    out: &mut String,
) -> Result<(), WriteError> {
    match &shape.kind {
        ShapeKind::Placeholder(ph) => {
            let Some(class) = odf_class(&ph.ph_type) else {
                ctx.report.warn(Warning::Degraded {
                    what: format!("a `{}` placeholder on page `{page}`", ph.ph_type.as_str()),
                    why: "PresentationML names it and ODF's closed presentation:class \
                          vocabulary does not, so there is no frame role to write it as \
                          and it was not written"
                        .into(),
                });
                return Ok(());
            };
            if class != ph.ph_type.as_str() && !is_exact_class(&ph.ph_type) {
                ctx.report.warn(Warning::Degraded {
                    what: format!(
                        "the role of a `{}` placeholder on page `{page}`",
                        ph.ph_type.as_str()
                    ),
                    why: format!(
                        "ODF's presentation:class has no `{}` and this frame was written \
as `{class}`, which is the nearest role the dialect names",
                        ph.ph_type.as_str()
                    ),
                });
            }
            // ODF distinguishes frames of one `presentation:class` by document
            // order alone; PresentationML numbers them. The number is real
            // information the dialect has no attribute for, so it is named here
            // — the reader will hand the first frame of a class no index at all
            // and every later one an ordinal of its own invention.
            if ph.idx.is_some_and(|idx| idx > 0) {
                ctx.report.warn(Warning::Degraded {
                    what: format!(
                        "the index of a `{}` placeholder on page `{page}`",
                        ph.ph_type.as_str()
                    ),
                    why: format!(
                        "PresentationML numbers a placeholder with `p:ph@idx` and ODF \
distinguishes frames of one presentation:class by document order alone, so index {} was \
not written",
                        ph.idx.unwrap_or(0)
                    ),
                });
            }
            let style = match class {
                "title" => "pr-title",
                "subtitle" => "pr-subtitle",
                _ => "pr-outline",
            };
            let box_attr = geometry_attr(shape).unwrap_or_else(|| {
                if class == "title" {
                    TITLE_BOX.to_string()
                } else {
                    BODY_BOX.to_string()
                }
            });
            let mut body = String::new();
            write_blocks(&with_list_styles(&ph.body), ctx, &mut body)?;
            out.push_str(&format!(
                r#"<draw:frame presentation:style-name="{style}" draw:layer="layout" {box_attr}{} presentation:class="{class}"><draw:text-box>{body}</draw:text-box></draw:frame>"#,
                name_attr(shape)
            ));
        }
        ShapeKind::TextBox { body } => {
            let mut inner = String::new();
            write_blocks(&with_list_styles(body), ctx, &mut inner)?;
            out.push_str(&format!(
                r#"<draw:frame draw:style-name="gr-plain" draw:layer="layout" {}{}><draw:text-box>{inner}</draw:text-box></draw:frame>"#,
                geometry_attr(shape).unwrap_or_else(|| BODY_BOX.to_string()),
                name_attr(shape)
            ));
        }
        ShapeKind::Picture(image) => write_picture(shape, image, ctx, out)?,
        ShapeKind::Table(table) => {
            let mut inner = String::new();
            write_blocks(
                std::slice::from_ref(&Block::Table(table.clone())),
                ctx,
                &mut inner,
            )?;
            out.push_str(&format!(
                r#"<draw:frame draw:style-name="gr-plain" draw:layer="layout" {}{}>{inner}</draw:frame>"#,
                geometry_attr(shape).unwrap_or_else(|| BODY_BOX.to_string()),
                name_attr(shape)
            ));
        }
        other => {
            let what = match other {
                ShapeKind::Chart(_) => "a chart",
                ShapeKind::Group(_) => "a group",
                ShapeKind::Raw(raw) => match raw.kind.as_str() {
                    "ole" => "an embedded object",
                    _ => "a preserved shape",
                },
                _ => "a shape",
            };
            let why = match other {
                ShapeKind::Chart(_) => {
                    "an ODF chart is a whole sub-document with its own content.xml and its \
                     own numbers, which this project writes for no dialect; this deck has \
                     no ODF package to copy one out of, so the chart was not written"
                }
                ShapeKind::Group(_) => {
                    "a `draw:g` is written by no writer in this project, and this deck has \
                     no ODF package to copy one out of, so the group was not written"
                }
                _ => {
                    "its markup was preserved from the dialect it was read in and this \
                     writer emits ODF, and this deck has no ODF package to copy it out of, \
                     so it was not written"
                }
            };
            ctx.report.warn(Warning::Degraded {
                what: format!("{what} on page `{page}`"),
                why: why.into(),
            });
        }
    }
    Ok(())
}

fn write_picture(
    shape: &Shape,
    image: &ImageRef,
    ctx: &mut WriterCtx<'_>,
    out: &mut String,
) -> Result<(), WriteError> {
    if let Some(url) = &image.external_src {
        ctx.report
            .warn(Warning::ExternalImageNotFetched { url: url.clone() });
        return Ok(());
    }
    let bytes = ctx.assets.get(&image.asset).ok_or_else(|| {
        WriteError::Asset(docsai_model::assets::AssetError::NotFound(
            image.asset.clone(),
        ))
    })?;
    let ext = ctx
        .assets
        .info(&image.asset)
        .map(|i| i.file_name.rsplit('.').next().unwrap_or("png").to_string())
        .unwrap_or_else(|| "png".into());
    ctx.pic_seq += 1;
    let path = format!("Pictures/image{:04}.{}", ctx.pic_seq, ext);
    ctx.pictures.insert(path.clone(), bytes.to_vec());

    // A picture states its rectangle in two halves, and which half is where
    // depends on where it came from. DocMark-P writes the size **once**, on the
    // image line, and deliberately leaves `Shape::geometry.size` empty
    // («the same measurement in two places is one that can disagree»,
    // `deck_parser::try_picture`), while the position rides on the shape. So a
    // frame is built from both: whichever states the position, and whichever
    // states the size. Requiring one source for both is what put every crossed
    // picture in the top-left corner.
    let (x, y) = match shape.geometry.pos {
        Some(pos) => (pos.x, pos.y),
        None => anchor_offset(&image.geometry.anchor),
    };
    let size = shape.geometry.size.unwrap_or(image.geometry.display_size);
    let box_attr = format!(
        r#"svg:x="{}" svg:y="{}" svg:width="{}" svg:height="{}""#,
        format_cm(x),
        format_cm(y),
        format_cm(size.width),
        format_cm(size.height)
    );
    let title = image
        .title
        .as_ref()
        .map(|t| format!("<svg:title>{}</svg:title>", crate::odt::write::esc_text(t)))
        .unwrap_or_default();
    // The reader takes `alt` from `svg:desc` and falls back to `svg:title`
    // (`odp/mod.rs`), so a `desc` equal to the title is markup that says
    // nothing and comes back the same either way.
    let alt = if image.alt.is_empty() || Some(&image.alt) == image.title.as_ref() {
        String::new()
    } else {
        format!(
            "<svg:desc>{}</svg:desc>",
            crate::odt::write::esc_text(&image.alt)
        )
    };
    out.push_str(&format!(
        r#"<draw:frame draw:style-name="gr-plain" draw:layer="layout" {box_attr}{}><draw:image xlink:href="{}" xlink:type="simple" xlink:show="embed" xlink:actuate="onLoad"/>{title}{alt}</draw:frame>"#,
        name_attr(shape),
        esc_attr(&path)
    ));
    Ok(())
}

/// Where a floating image sits, as far as ODF can be told about it.
///
/// A symbolic alignment (`left`, `center`) is not a number and a page frame
/// takes a number, so it resolves to the axis origin — which is what an ODF
/// consumer draws for a frame whose `svg:x` it does not have either.
fn anchor_offset(anchor: &Anchor) -> (Length, Length) {
    let Anchor::Floating { position, .. } = anchor else {
        return (Length::ZERO, Length::ZERO);
    };
    let axis = |a: &AxisPos| match a {
        AxisPos::Offset(length) => *length,
        AxisPos::Align(_) => Length::ZERO,
    };
    (axis(&position.h), axis(&position.v))
}

/// `draw:name`, when the model states one.
fn name_attr(shape: &Shape) -> String {
    match &shape.name {
        Some(name) => format!(r#" draw:name="{}""#, esc_attr(name)),
        None => String::new(),
    }
}

/// The frame rectangle, when the model states a whole one.
///
/// A position without a size, or a size without a position, is not a rectangle
/// ODF can be told about — `svg:x` with no `svg:width` is a frame of unstated
/// width — so the layout's own rectangle is used instead, which is what the
/// absent half meant.
fn geometry_attr(shape: &Shape) -> Option<String> {
    let pos = shape.geometry.pos?;
    let size = shape.geometry.size?;
    Some(format!(
        r#"svg:x="{}" svg:y="{}" svg:width="{}" svg:height="{}""#,
        format_cm(pos.x),
        format_cm(pos.y),
        format_cm(size.width),
        format_cm(size.height)
    ))
}

/// [`PhType`] → `presentation:class`, the inverse of the reader's own map.
///
/// Eleven types map straight back. Three do not and each is answered
/// differently, because the three questions are different:
///
/// * **`ctrTitle`** is `title`. ODF has one title role and PresentationML has
///   two, so the distinction is real and is lost — [`is_exact_class`] is what
///   makes the caller say so.
/// * **`clipArt`, `media`** are `object`, for the same reason and with the same
///   warning: ODF's closed vocabulary names neither, and `object` is what an
///   embedded thing of an unnamed kind is.
/// * **`sldImg`** is `page`, which is the same construct under the other
///   dialect's word, so nothing is lost and nothing is said.
///
/// [`PhType::Other`] carrying a word ODF does name — `text`, which 18-B put
/// there precisely because PresentationML has no keyword for it — goes back as
/// itself.
fn odf_class(ph: &PhType) -> Option<&'static str> {
    Some(match ph {
        PhType::Title | PhType::CenterTitle => "title",
        PhType::Subtitle => "subtitle",
        PhType::Body => "outline",
        PhType::Object | PhType::ClipArt | PhType::Media => "object",
        PhType::Chart => "chart",
        PhType::Table => "table",
        PhType::Picture => "graphic",
        PhType::Diagram => "orgchart",
        PhType::Header => "header",
        PhType::Footer => "footer",
        PhType::DateTime => "date-time",
        PhType::SlideNumber => "page-number",
        PhType::Other(word) => match word.as_str() {
            "sldImg" => "page",
            "text" => "text",
            "notes" => "notes",
            _ => return None,
        },
    })
}

/// Whether the class [`odf_class`] chose says everything the type did.
///
/// A `title` frame written from `PhType::Title` is exact; one written from
/// `PhType::CenterTitle` is not, and the difference is a warning rather than a
/// silence.
fn is_exact_class(ph: &PhType) -> bool {
    !matches!(ph, PhType::CenterTitle | PhType::ClipArt | PhType::Media)
}
