//! The `draw:page` the package does not have (Phase 18, increment 18-E).
//!
//! Everywhere else the `.odp` writer [splices](super::write): the part is the
//! one that was read, and what comes from the model is the paragraphs inside a
//! `draw:text-box`. That rule needs a package to splice into, and 18-D refused
//! to invent one — correctly, because a deck read from a `.odp` always has its
//! own.
//!
//! **18-E is the case that argument does not cover.** A deck read from a
//! `.pptx` carries an OPC package in its skeleton, and no amount of care makes
//! that an ODF package: it has no `content.xml`, no `office:presentation` and
//! no `draw:page`. So for the cross conversion the choice is not between
//! splicing and generating, it is between generating **with the substitution
//! said out loud** and refusing a conversion the plan asks for by name.
//!
//! This module is the generating half. It writes an `office:presentation` body
//! from the model, into the template `docsai-odf` embeds, and then hands the
//! result to the ordinary writer — so a generated page reaches the archive
//! through exactly the same door a preserved one does, and every comparison,
//! every splice and every warning downstream is the one 18-D already wrote.
//!
//! ## What it writes, and what it names instead of writing
//!
//! | the model's shape | the page gets |
//! | --- | --- |
//! | a placeholder | `draw:frame` with its `presentation:class` and a text box |
//! | a text box | `draw:frame` with a graphic style and a text box |
//! | a picture | `draw:frame` with a `draw:image`, and the bytes in `Pictures/` |
//! | a table | `draw:frame` with the `table:table` the ODF block writer renders |
//! | speaker notes | `presentation:notes` with a notes frame |
//! | a chart | **nothing**, and a `Degraded` warning naming it and its dialect |
//! | a group, an OLE object, a preserved shape | the same |
//! | a comment | the same |
//!
//! The three that are named rather than written are named for one reason each,
//! and none of them is «not implemented yet»: an ODF chart is a whole
//! sub-document with its own `content.xml` and its own numbers, an OLE payload
//! is a stream this project never produced, and an ODF annotation is markup no
//! writer in this project writes ([[101-phase-18-odp-writer]] says so about the
//! splicing path too). Writing an empty frame for any of them would be a file
//! that looks like a success.

